package com.d2rei.buddyoverlay

import androidx.room.Entity
import androidx.room.PrimaryKey

@Entity(tableName = "buddy_settings")
data class BuddySettingsEntity(
    @PrimaryKey val id: Int = 1,
    val excitedThresholdEp: Int = BuddyGameplayDefaults.excitedThresholdEp,
    val decayIntervalMinutes: Int = BuddyGameplayDefaults.decayIntervalMinutes,
    val decayAmountEp: Int = BuddyGameplayDefaults.decayAmountEp,
    val bubbleOpacity: Float = BuddyGameplayDefaults.bubbleOpacity,
    val bubbleSizeDp: Int = BuddyGameplayDefaults.bubbleSizeDp,
    val panelOpacity: Float = BuddyGameplayDefaults.panelOpacity,
    val vibrationEnabled: Boolean = BuddyGameplayDefaults.vibrationEnabled,
    val readyNotificationsEnabled: Boolean = BuddyGameplayDefaults.readyNotificationsEnabled,
    val swapEp: Int = BuddyGameplayDefaults.defaultEpByAction.getValue(BuddyActionType.SWAP),
    val giftEp: Int = BuddyGameplayDefaults.defaultEpByAction.getValue(BuddyActionType.GIFT),
    val careEp: Int = BuddyGameplayDefaults.defaultEpByAction.getValue(BuddyActionType.CARE),
    val routeEp: Int = BuddyGameplayDefaults.defaultEpByAction.getValue(BuddyActionType.ROUTE),
    val walkEp: Int = BuddyGameplayDefaults.defaultEpByAction.getValue(BuddyActionType.WALK_2KM),
    val rocketEp: Int = BuddyGameplayDefaults.defaultEpByAction.getValue(BuddyActionType.BATTLE_ROCKET),
    val leaderEp: Int = BuddyGameplayDefaults.defaultEpByAction.getValue(BuddyActionType.BATTLE_LEADER),
    val gymRaidEp: Int = BuddyGameplayDefaults.defaultEpByAction.getValue(BuddyActionType.BATTLE_GYM_RAID),
    val pvpEp: Int = BuddyGameplayDefaults.defaultEpByAction.getValue(BuddyActionType.BATTLE_PVP),
    val swapCooldownMinutes: Int = BuddyGameplayDefaults.defaultCooldownMinutesByAction.getValue(BuddyActionType.SWAP),
    val giftCooldownMinutes: Int = BuddyGameplayDefaults.defaultCooldownMinutesByAction.getValue(BuddyActionType.GIFT),
    val careCooldownMinutes: Int = BuddyGameplayDefaults.defaultCooldownMinutesByAction.getValue(BuddyActionType.CARE),
    val routeCooldownMinutes: Int = BuddyGameplayDefaults.defaultCooldownMinutesByAction.getValue(BuddyActionType.ROUTE),
    val walkCooldownMinutes: Int = BuddyGameplayDefaults.defaultCooldownMinutesByAction.getValue(BuddyActionType.WALK_2KM),
    val rocketCooldownMinutes: Int = BuddyGameplayDefaults.defaultCooldownMinutesByAction.getValue(BuddyActionType.BATTLE_ROCKET),
    val leaderCooldownMinutes: Int = BuddyGameplayDefaults.defaultCooldownMinutesByAction.getValue(BuddyActionType.BATTLE_LEADER),
    val gymRaidCooldownMinutes: Int = BuddyGameplayDefaults.defaultCooldownMinutesByAction.getValue(BuddyActionType.BATTLE_GYM_RAID),
    val pvpCooldownMinutes: Int = BuddyGameplayDefaults.defaultCooldownMinutesByAction.getValue(BuddyActionType.BATTLE_PVP),
) {
    fun toModel(): BuddySettings = BuddySettings(
        excitedThresholdEp = excitedThresholdEp,
        decayIntervalMinutes = decayIntervalMinutes,
        decayAmountEp = decayAmountEp,
        bubbleOpacity = bubbleOpacity,
        bubbleSizeDp = bubbleSizeDp,
        panelOpacity = panelOpacity,
        vibrationEnabled = vibrationEnabled,
        readyNotificationsEnabled = readyNotificationsEnabled,
        actionEpMap = mapOf(
            BuddyActionType.SWAP to swapEp,
            BuddyActionType.GIFT to giftEp,
            BuddyActionType.CARE to careEp,
            BuddyActionType.ROUTE to routeEp,
            BuddyActionType.WALK_2KM to walkEp,
            BuddyActionType.BATTLE_ROCKET to rocketEp,
            BuddyActionType.BATTLE_LEADER to leaderEp,
            BuddyActionType.BATTLE_GYM_RAID to gymRaidEp,
            BuddyActionType.BATTLE_PVP to pvpEp,
        ),
        cooldownMinutesMap = mapOf(
            BuddyActionType.SWAP to swapCooldownMinutes,
            BuddyActionType.GIFT to giftCooldownMinutes,
            BuddyActionType.CARE to careCooldownMinutes,
            BuddyActionType.ROUTE to routeCooldownMinutes,
            BuddyActionType.WALK_2KM to walkCooldownMinutes,
            BuddyActionType.BATTLE_ROCKET to rocketCooldownMinutes,
            BuddyActionType.BATTLE_LEADER to leaderCooldownMinutes,
            BuddyActionType.BATTLE_GYM_RAID to gymRaidCooldownMinutes,
            BuddyActionType.BATTLE_PVP to pvpCooldownMinutes,
        ),
    )

    companion object {
        fun fromModel(model: BuddySettings) = BuddySettingsEntity(
            excitedThresholdEp = model.excitedThresholdEp,
            decayIntervalMinutes = model.decayIntervalMinutes,
            decayAmountEp = model.decayAmountEp,
            bubbleOpacity = model.bubbleOpacity,
            bubbleSizeDp = model.bubbleSizeDp,
            panelOpacity = model.panelOpacity,
            vibrationEnabled = model.vibrationEnabled,
            readyNotificationsEnabled = model.readyNotificationsEnabled,
            swapEp = model.epFor(BuddyActionType.SWAP),
            giftEp = model.epFor(BuddyActionType.GIFT),
            careEp = model.epFor(BuddyActionType.CARE),
            routeEp = model.epFor(BuddyActionType.ROUTE),
            walkEp = model.epFor(BuddyActionType.WALK_2KM),
            rocketEp = model.epFor(BuddyActionType.BATTLE_ROCKET),
            leaderEp = model.epFor(BuddyActionType.BATTLE_LEADER),
            gymRaidEp = model.epFor(BuddyActionType.BATTLE_GYM_RAID),
            pvpEp = model.epFor(BuddyActionType.BATTLE_PVP),
            swapCooldownMinutes = (model.cooldownMinutesMap[BuddyActionType.SWAP] ?: 0),
            giftCooldownMinutes = (model.cooldownMinutesMap[BuddyActionType.GIFT] ?: 0),
            careCooldownMinutes = (model.cooldownMinutesMap[BuddyActionType.CARE] ?: 0),
            routeCooldownMinutes = (model.cooldownMinutesMap[BuddyActionType.ROUTE] ?: 0),
            walkCooldownMinutes = (model.cooldownMinutesMap[BuddyActionType.WALK_2KM] ?: 0),
            rocketCooldownMinutes = (model.cooldownMinutesMap[BuddyActionType.BATTLE_ROCKET] ?: 0),
            leaderCooldownMinutes = (model.cooldownMinutesMap[BuddyActionType.BATTLE_LEADER] ?: 0),
            gymRaidCooldownMinutes = (model.cooldownMinutesMap[BuddyActionType.BATTLE_GYM_RAID] ?: 0),
            pvpCooldownMinutes = (model.cooldownMinutesMap[BuddyActionType.BATTLE_PVP] ?: 0),
        )
    }
}
