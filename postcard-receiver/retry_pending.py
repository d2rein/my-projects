from __future__ import annotations

import json
from pathlib import Path

import postcard_receiver


ROOT = Path(__file__).resolve().parent
PENDING_DIR = ROOT / "data" / "pending"
RECOVERED_DIR = ROOT / "data" / "processed-retries"


def main() -> None:
    screenshots = sorted(PENDING_DIR.glob("pending-*.jpg"))
    recovered = 0
    unresolved = 0
    for index, screenshot in enumerate(screenshots, start=1):
        metadata_path = screenshot.with_suffix(".json")
        metadata = json.loads(metadata_path.read_text(encoding="utf-8")) if metadata_path.exists() else {}
        source_id = metadata.get("sourceId", "1")
        before = set(PENDING_DIR.glob("pending-*"))
        success, message = postcard_receiver.process_postcard(screenshot.read_bytes(), source_id)
        generated = set(PENDING_DIR.glob("pending-*")) - before
        if success:
            RECOVERED_DIR.mkdir(parents=True, exist_ok=True)
            screenshot.replace(RECOVERED_DIR / screenshot.name)
            if metadata_path.exists():
                metadata_path.replace(RECOVERED_DIR / metadata_path.name)
            recovered += 1
        else:
            # process_postcard retained a fresh copy; the existing review pair
            # is canonical, so remove only the duplicate generated by this retry.
            for path in generated:
                path.unlink(missing_ok=True)
            unresolved += 1
        print(f"[{index}/{len(screenshots)}] {message}", flush=True)
    print(f"Recovered {recovered}; still needs review {unresolved}")


if __name__ == "__main__":
    main()
